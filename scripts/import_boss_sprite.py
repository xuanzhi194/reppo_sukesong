"""Mechanically import the generated 4-frame atlas as LVGL RGB565+A8."""
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parents[1]
im = Image.open(root / 'assets/boss/boss_sheet.png').convert('RGBA')
w, h = im.size
# Identical crop and scaling for all cells preserves the animation baseline.
frames = [im.crop((i*w//4, 90, (i+1)*w//4, 620)) for i in range(4)]
frames = [f.resize((76, 76), Image.Resampling.NEAREST) for f in frames]
lines = ['/* Generated by scripts/import_boss_sprite.py; LV_COLOR_DEPTH=16. */', '#include "lvgl.h"']
for i, f in enumerate(frames):
    data = []
    for r,g,b,a in f.getdata():
        c = ((r>>3)<<11) | ((g>>2)<<5) | (b>>3)
        data.extend((c & 255, c >> 8, a))
    lines.append(f'static const uint8_t boss_{i}_data[] = {{')
    lines += [','.join(f'0x{v:02x}' for v in data[j:j+24])+',' for j in range(0,len(data),24)]
    lines.append('};')
    lines.append(f'const lv_img_dsc_t boss_sprite_{i} = {{ .header = {{.cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .w = 76, .h = 76}}, .data_size = sizeof(boss_{i}_data), .data = boss_{i}_data }};')
    f.save(root / f'assets/boss/frame_{i}.png')
(root / 'components/ui_custom/custom/assets/boss_sprite.c').write_text('\n'.join(lines)+'\n')
print('Imported four 76x76 RGBA sprites; 69,312 bytes in firmware')
