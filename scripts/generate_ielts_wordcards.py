MAX_WORD = 31
MAX_PHONETIC = 31
MAX_DEF = 63


def to_phonetic(word: str) -> str:
    raw = ipa.convert(word.lower()).strip()
    if not raw or "*" in raw:
        return f"[{word.lower()}]"
    text = f"[{raw}]"
    if len(text) > MAX_PHONETIC:
        text = text[: MAX_PHONETIC - 1] + "]"
    return text


def clamp_field(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    return text[: limit - 3] + "..."


def load_legacy_supplement() -> list[tuple[str, str]]:
    """Load prior in-project word list as fill vocabulary (Word, definition)."""
    if not LEGACY_SUPPLEMENT.is_file():
        return []

    rows: list[tuple[str, str]] = []
    with LEGACY_SUPPLEMENT.open(encoding="utf-8-sig") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split(",", 2)
            if len(parts) != 3:
                continue
            word, _phonetic, definition = parts
            word = word.strip()
            definition = definition.strip()
            if word and definition:
                rows.append((word, definition))
    return rows


def merge_entries() -> list[tuple[str, str, str]]:
    seen: set[str] = set()
    merged: list[tuple[str, str, str]] = []

    for word, pos, zh in ENTRIES + TOPIC_SUPPLEMENTS:
        key = word.lower()
        if key in seen:
            continue
        seen.add(key)
        definition = f"{pos} {zh}" if pos else zh
        merged.append((word, pos, definition))

    for word, definition in load_legacy_supplement():
        if len(merged) >= TARGET_COUNT:
            break
        key = word.lower()
        if key in seen:
            continue
        seen.add(key)
        merged.append((word, "", definition))

    merged.sort(key=lambda item: item[0].lower())
    return merged[:TARGET_COUNT]


def validate(entries: list[tuple[str, str, str]]) -> None:
    for word, _, definition in entries:
        if len(word) > MAX_WORD:
            raise ValueError(f"word too long: {word!r}")
        phonetic = to_phonetic(word)
        if len(phonetic) > MAX_PHONETIC:
            raise ValueError(f"phonetic too long: {word!r} -> {phonetic!r}")
        if len(definition) > MAX_DEF:
            raise ValueError(f"definition too long: {word!r} -> {definition!r}")


def write_csv(entries: list[tuple[str, str, str]]) -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        for word, _, definition in entries:
            writer.writerow([
                clamp_field(word, MAX_WORD),
                to_phonetic(word),
                clamp_field(definition, MAX_DEF),
            ])


def main() -> None:
    entries = merge_entries()
    validate(entries)
    write_csv(entries)
    print(f"Wrote {len(entries)} entries to {OUT} (target {TARGET_COUNT})")


if __name__ == "__main__":
    main()
